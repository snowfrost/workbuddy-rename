# 前缀：任意盘符 + ...\WorkBuddy\ ，兼容 JSON-in-TEXT 转义后的双反斜杠
_PREFIX = r'([A-Za-z]:[/\\]{1,2}[^"?*<>|\r\n]*?[Ww]ork[Bb]uddy[/\\]{1,2})'

# 旧目录名按长度降序，避免短名先命中长名前缀
PATS = [(re.compile(_PREFIX + re.escape(old) + r'(?=[/\\]|["\']|$|\s|,|})'), new)
        for old, new in sorted(MAP.items(), key=lambda kv: len(kv[0]), reverse=True)]

_SEP_TAIL = re.compile(r'([/\\]+)$')


def fix_paths_in_text(s):
    """替换字符串中的旧路径，保持原分隔符数量与风格。返回 (新串, 命中数)。"""
    hits = 0

    def _repl(new):
        def f(m):
            nonlocal hits
            prefix = m.group(1)
            tail = _SEP_TAIL.search(prefix)
            sep = tail.group(1) if tail else '\\'
            hits += 1
            return prefix + new.replace('/', sep)
        return f

    for pat, new in PATS:
        s = pat.sub(_repl(new), s)
    return s, hits
